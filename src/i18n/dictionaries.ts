/** Dot-path keys such as `"nav.home"` or `"pages.about.title"`. */
type Paths<T, P extends string = ""> = {
  [K in keyof T & string]: T[K] extends string ? `${P}${K}` : Paths<T[K], `${P}${K}.`>;
}[keyof T & string];

export type TKey = Paths<Dictionary>;

export function translate(locale: Locale, key: TKey): string {
  const parts = key.split(".");
  let node: unknown = dictionaries[locale];
  for (const p of parts) {
    node = (node as Record<string, unknown> | undefined)?.[p];
  }
  if (typeof node === "string") return node;
  // Fallback to English
  let fallback: unknown = dictionaries.en;
  for (const p of parts) {
    fallback = (fallback as Record<string, unknown> | undefined)?.[p];
  }
  return typeof fallback === "string" ? fallback : key;
}
